from pathlib import Path

from .brain import Brain
from .records import Records, split_front_matter

START = "<!-- brain:index:start (generated by brain index; do not edit) -->"
END = "<!-- brain:index:end -->"
OPENING_START = "<!-- brain:opening:start (generated by brain index; do not edit) -->"
OPENING_END = "<!-- brain:opening:end -->"
AGENT_START = "<!-- brain:agent:start (generated from agent.md by brain index; do not edit) -->"
AGENT_END = "<!-- brain:agent:end -->"
FIRST_PROCEDURE = "take-feedback"
VOICE_LINES = 12
# Past these, the team index lists policies only in references/policies/, so SKILL.md stays loadable.
TEAM_MAX_AGENTS = 100
TEAM_MAX_POLICIES = 100
ROUTINES_LINE = "The team's routines are in [references/routines/](references/routines/): when each runs, who runs it, and which procedure."


def items(value) -> list[str]:
    if isinstance(value, dict):
        return [f"{k}: {v}" for k, v in value.items()]
    if isinstance(value, list):
        return [", ".join(f"{k}: {v}" for k, v in i.items()) if isinstance(i, dict) else str(i) for i in value]
    return [str(value)] if value not in (None, "") else []


def render_agent(records: Records, team: str | None = None, lanes: list[str] | None = None) -> str:
    # agent.md loads only when the agent follows a link, so its limits are copied where every load sees them.
    agent = records.agent
    meta = agent.meta if agent else {}
    lines = [AGENT_START, "## Your job", ""]
    if meta.get("job"):
        lines += [str(meta["job"]).strip(), ""]
    if team:
        lines += [f"**Team:** {team}. The team's policies are in the {team} skill.", ""]
    for label, key in (("Your lane", "lane"), ("Never", "anti_jobs"), ("Ask first", "needs_approval"), ("Roles you hand off to or consult", "roles")):
        # In a team, the lane rows come from the team's lanes.md, so the hand-off and consult procedures still find them here.
        values = list(lanes or []) if team and key == "lane" else items(meta.get(key))
        if values:
            lines += [f"**{label}:**", *[f"- {v}" for v in values], ""]
    for label, key in (("Your skills", "skills"), ("Your books", "books")):
        if items(meta.get(key)):
            lines += [f"**{label}:**", *[f"- {v}" for v in items(meta.get(key))], ""]
    if meta.get("decider"):
        lines += [f"**Decider:** {meta['decider']}, who approves changes to this brain and settles conflicts.", ""]
    voice = (agent.sections.get("Voice", "") if agent else "").strip().splitlines()
    if voice:
        shown = voice[:VOICE_LINES]
        more = ["", "The full voice is in [agent.md](agent.md)."] if len(voice) > VOICE_LINES else []
        lines += ["## Your voice", "", *shown, *more, ""]
    lines.append(AGENT_END)
    return "\n".join(lines)


def current_agent(skill_text: str) -> str | None:
    start = skill_text.find(AGENT_START)
    end = skill_text.find(AGENT_END)
    if start == -1 or end == -1 or end < start:
        return None
    return skill_text[start : end + len(AGENT_END)]


def by_topic(records: Records, active: list) -> list[str]:
    topics = records.by_folder["topics"]
    # A rule or policy sits under its first topic only, so each row appears once. check blocks one with no topic.
    groups: dict[str, list] = {}
    for record in active:
        labels = record.meta.get("topics") or [""]
        groups.setdefault(str(labels[0]), []).append(record)

    def topic_title(key: str) -> str:
        return str(topics[key].meta.get("name", key)) if key in topics else key

    lines = []
    for key in sorted(groups, key=lambda k: topic_title(k).lower()):
        lines += [f"### {topic_title(key)}", ""]
        for record in sorted(groups[key], key=lambda r: str(r.meta.get("name", "")).lower()):
            lines.append(row(record))
        lines.append("")
    return lines


def render(records: Records) -> str:
    rules = [r for r in records.by_folder["rules"].values() if r.meta.get("status") == "active"]
    procedures = [p for p in records.by_folder["procedures"].values() if p.meta.get("status") == "active"]

    lines = [START, "## Rules", ""]
    if not rules:
        lines += ["No active rules yet.", ""]
    lines += by_topic(records, rules)

    lines += ["## Procedures", ""]
    if not procedures:
        lines += ["No active procedures yet.", ""]
    ordered = sorted(procedures, key=lambda p: (p.id != FIRST_PROCEDURE, str(p.meta.get("name", "")).lower()))
    for procedure in ordered:
        lines.append(row(procedure, trigger=True))
    if procedures:
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def render_team(brain: Brain, records: Records, repo: Path | None) -> str:
    from . import team
    from .records import load

    lanes, _ = team.parse_lanes(records, "")
    entries = sorted(team.roster(brain, repo).items())
    policies = [p for p in records.by_folder["policies"].values() if p.meta.get("status") == "active"]
    lines = [START, "## Roster", ""]
    if not entries:
        lines += ["No agents yet.", ""]
    for name, source in entries:
        agent = team.brain_at(repo, source) if repo else None
        agent_md = load(agent).agent if agent and not agent.is_team else None
        meta = agent_md.meta if agent_md else {}
        title = meta.get("display_name") or name
        job = str(meta.get("job") or meta.get("description") or "(no agent brain)").strip()
        owned = "; ".join(lane.work for lane in lanes if lane.owner == name) or "none"
        lines.append(f"- **{title}** ({name}). {job} Lanes: {owned}.")
    if entries:
        lines.append("")
    lines += ["## Policies", ""]
    if not policies:
        lines += ["No active policies yet.", ""]
    elif len(entries) > TEAM_MAX_AGENTS or len(policies) > TEAM_MAX_POLICIES:
        lines += [f"The team has {len(policies)} active policies, too many to list here. Search [references/policies/](references/policies/) by topic.", ""]
    else:
        lines += by_topic(records, policies)
    lines += ["## Routines", "", ROUTINES_LINE, "", END]
    return "\n".join(lines)


def row(record, trigger: bool = False) -> str:
    name = str(record.meta.get("name", record.id)).rstrip(".")
    text = str(record.meta.get("description", "")).strip()
    if trigger and record.meta.get("trigger"):
        text = f"When: {str(record.meta['trigger']).strip()} {text}"
    return f"- **{name}.** {text} [{record.ref}](references/{record.ref}.md)"


def current_block(text: str, start: str, end: str) -> str | None:
    i, j = text.find(start), text.find(end)
    return text[i : j + len(end)] if i != -1 and j > i else None


def current(skill_text: str) -> str | None:
    start = skill_text.find(START)
    end = skill_text.find(END)
    if start == -1 or end == -1 or end < start:
        return None
    return skill_text[start : end + len(END)]


def render_skill(brain: Brain, records: Records, repo: Path | None, text: str) -> str:
    # The whole SKILL.md is generated. Only its front matter, the description first, is written by hand, and it is kept as written.
    from . import team
    from .scaffold import template

    end = text.find("\n---\n", 4) if text.startswith("---\n") else -1
    front = text[4 : end + 1] if end != -1 else f"name: {brain.name}\ndescription: \"\"\n"
    if brain.is_team:
        body = template("team/SKILL.md", brain.name)
        blocks = {START: render_team(brain, records, team.repo_root(brain, repo))}
    else:
        display = records.agent.meta.get("display_name") if records.agent else None
        body = template("SKILL.md", brain.name, display if isinstance(display, str) and display else brain.name)
        blocks = {AGENT_START: render_agent(records, brain.team, team.lanes_of(brain, team.repo_root(brain, repo))), START: render(records)}
    _, body = split_front_matter(body)
    for start, block in blocks.items():
        end = AGENT_END if start == AGENT_START else END
        body = body.replace(f"{start}\n{end}", block, 1)
    return f"---\n{front}---\n{body}"


def outside_blocks(text: str) -> str:
    # What is left of the body once the generated blocks are taken out, with spacing ignored.
    body = split_front_matter(text)[1] if text.startswith("---\n") else text
    for start, end in ((OPENING_START, OPENING_END), (AGENT_START, AGENT_END), (START, END)):
        i, j = body.find(start), body.find(end)
        if i != -1 and j > i:
            body = body[:i] + body[j + len(end) :]
    return " ".join(body.split())


def hand_written(brain: Brain, text: str) -> bool:
    # Only the front matter is written by hand: anything else outside the blocks differs from the template.
    from .scaffold import template

    fresh = template("team/SKILL.md" if brain.is_team else "SKILL.md", brain.name)
    return outside_blocks(text) != outside_blocks(fresh)


def replace_blocks(brain: Brain, records: Records, repo: Path | None, text: str) -> str:
    from . import team

    old = current(text)
    if old is None:
        return text
    opening = current_block(render_skill(brain, records, repo, text), OPENING_START, OPENING_END)
    old_opening = current_block(text, OPENING_START, OPENING_END)
    if opening is not None and old_opening is not None:
        text = text.replace(old_opening, opening, 1)
    if brain.is_team:
        return text.replace(old, render_team(brain, records, team.repo_root(brain, repo)), 1)
    agent_block = render_agent(records, brain.team, team.lanes_of(brain, team.repo_root(brain, repo)))
    old_agent = current_agent(text)
    text = text.replace(old_agent, agent_block, 1) if old_agent is not None else text.replace(old, f"{agent_block}\n\n{old}", 1)
    return text.replace(current(text), render(records), 1)


def write(brain: Brain, records: Records, repo: Path | None = None, replace: bool = False) -> bool:
    # A file with hand-written text outside the description keeps it until brain index --replace, so nothing is lost by a link or a status change.
    text = brain.skill_file.read_text()
    if replace or not hand_written(brain, text):
        new_text = render_skill(brain, records, repo, text)
        if new_text != text:
            brain.skill_file.write_text(new_text)
        return True
    if current(text) is None:
        return False
    new_text = replace_blocks(brain, records, repo, text)
    if new_text != text:
        brain.skill_file.write_text(new_text)
    return True
